require('../extension/lib/core.js');
const M = globalThis.MCL, assert = require('assert'), K = M.key;
assert.equal(M.pageKey('/app/groups/11/management'), '/app/groups/:id/management');
assert.equal(M.patternOf('http://localhost:3000'), 'http://localhost/*');
assert.equal(M.originOf('https://a.b.ch/x?y'), 'https://a.b.ch');
assert.equal(M.originOf('chrome://extensions'), null);
const csv = 'screen;typ;original;A;B;notiz;gefunden\n/app;text;Willkommen zurück,;Hallo,;Guten Tag,;;\n*;text;Geräte;Sensoren;Matten;;\n/app;text;{n} Geräte;{n} Sensoren;{x} Matten;;\n/app/groups/*;text;Meldungen;Alarme;;;\n*;text;Geräte;X;;;\n;;;;;hi;\n*;Platzhalter;"Suchen; bitte";Zimmer suchen;;;\n*;text;+ Neu;= Neu;;;\n';
const { table, report } = M.buildTable(M.parseCSV(csv), new Set([K('text', 'Geräte')]));
assert.deepEqual(report.variants, ['A', 'B']); assert.equal(report.rowCount, 6); assert.equal(report.warnings.length, 2);
const c = M.compileTable(table);
assert.equal(M.lookup(c, ' Geräte ', 'text', '/app', 'A').value, 'Sensoren');
assert.equal(M.lookup(c, '2 Geräte', 'text', '/app', 'A').value, '2 Sensoren');
assert.equal(M.lookup(c, 'Meldungen', 'text', '/app/groups/:id/x', 'A').value, 'Alarme');
assert.equal(M.lookup(c, 'Meldungen', 'text', '/app', 'A'), null);
assert.equal(M.lookup(c, 'Suchen; bitte', 'placeholder', '/x', 'A').value, 'Zimmer suchen');
const m = M.exportMatrix(table, { [K('text', 'Neu hier')]: { pages: ['/app'] } });
assert.deepEqual(m[0], ['page', 'type', 'original', 'A', 'B', 'note', 'found']);
const rt = M.buildTable(M.parseCSV(M.toCSV(m)), null);
assert.equal(rt.report.rowCount, 7);
assert.ok(rt.table.rows.some(r => r.original === '+ Neu' && r.values.A === '= Neu'), 'formula guard roundtrip');
assert.ok(M.toCSV([['=1+1']]).includes("'=1+1"));
assert.deepEqual(M.sheetPermissionOrigins('https://docs.google.com/spreadsheets/d/x/edit'), ['https://docs.google.com/*', 'https://*.googleusercontent.com/*']);
console.log('CORE OK');
